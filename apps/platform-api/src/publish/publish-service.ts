// Docker builds run on the host shared by every workspace. Serialize deploy work process-wide so
// one project's image build cannot starve another project's active development container.
let deployQueue: Promise<void> = Promise.resolve();
async function withDeployQueue<T>(operation: () => Promise<T>): Promise<T> {
  const previous = deployQueue;
  let release: () => void;
  deployQueue = new Promise<void>((resolve) => {
    release = resolve;
  });
  await previous;
  try {
    return await operation();
  } finally {
    release!();
  }
}
// Production image recipe for the generated Next.js apps. `next build` → `next start` yields a REAL
// prod artifact: it boots in ~1s with no install-on-start, unlike the old `docker commit` snapshot
// of the dev container (which re-ran `npm install` + `next dev` on every boot). Written into the
// source container's /workspace at publish time and built via the Docker Engine `/build` API.
export const PRODUCTION_DOCKERFILE = `FROM node:20-alpine
WORKDIR /app
COPY package*.json ./
RUN npm ci --no-audit --no-fund
COPY . .
RUN npm run build
ENV NODE_ENV=production
EXPOSE 3000
CMD ["npm","start"]
`;
// Keeps the build context lean and correct: node_modules is reinstalled by \`npm ci\`, .next is
// regenerated by \`npm run build\`, and .git is irrelevant to the runtime image.
export const PRODUCTION_DOCKERIGNORE = `node_modules
.next
.git
`;
/**
 * The generated app's locked next.config.js reads EVCP_PREVIEW_BASE during `next build`. Inject
 * an environment file only into the in-memory build context so each deployment emits navigation
 * and asset URLs that return through its proxy, without replacing user config or touching dev.
 */
export function buildDeploymentEnvironment(slug: string, environment: EnvironmentName): string {
  const basePath = environment === "staging" ? `/apps/${slug}/staging` : `/apps/${slug}`;
  return `EVCP_PREVIEW_BASE=${basePath}\n`;
}
function deploymentContainerName(
  slug: string,
  environment: EnvironmentName,
  revisionSuffix: string
): string {
  const prefix = `evcp-${environment}-`;
  const suffix = `-${revisionSuffix}`;
  const maxDnsLabelLength = 63;
  const slugLength = Math.max(1, maxDnsLabelLength - prefix.length - suffix.length);
  return `${prefix}${slug.slice(0, slugLength)}${suffix}`;
}
export type PublishOutcome =
  | { ok: true; deployment: WorkspaceDeployment }
  | { ok: false; reason: "pre_checks_failed"; failures: string[] }
  | { ok: false; reason: "health_failed"; deployment: WorkspaceDeployment };
export interface PublishServiceDeps {
  docker: DockerEngine;
  git: GitPort;
  migrations: MigrationStore;
  deployments: DeploymentStore;
  health: HealthChecker;
  resolveEnv: (projectId: string) => Promise<Record<string, string>>;
  getDevContainerId: (projectId: string) => string | Promise<string>;
  network?: string;
  onAudit?: (event: {
    action: string;
    projectId: string;
    metadata?: Record<string, unknown>;
  }) => void;
  lifecycle?: ProjectLifecycleCoordinator;
}
export function createPublishService(deps: PublishServiceDeps) {
  const network = deps.network ?? "evcp-internal";
  const projectLocks = new Map<string, Promise<void>>();
  const audit = (action: string, projectId: string, metadata?: Record<string, unknown>) =>
    deps.onAudit?.({ action, projectId, metadata });
  const withLifecycle = <T>(projectId: string, operation: (fence?: ProjectMutationFence) => Promise<T>) =>
    deps.lifecycle ? deps.lifecycle.runChildMutation(projectId, operation) : operation();
  // A rollback changes the source workspace's checked-out commit, and all publish operations share
  // the same per-project Docker resources. Keep each project's deploy lifecycle atomic in-process.
  const withProjectLock = async <T>(projectId: string, operation: () => Promise<T>): Promise<T> => {
    const previous = projectLocks.get(projectId) ?? Promise.resolve();
    let release: () => void;
    const current = new Promise<void>((resolve) => {
      release = resolve;
    });
    projectLocks.set(projectId, current);
    await previous;
    try {
      return await operation();
    } finally {
      release!();
      if (projectLocks.get(projectId) === current) projectLocks.delete(projectId);
    }
  };
  // publish builds a fresh production image from the dev container's /workspace source. The
  // Dockerfile/.dockerignore are injected into the build-context tar in memory (not written to
  // /workspace) so the app's git tree stays clean and re-publish stays idempotent.
  const buildProductionImage = async (
    sourceContainerId: string,
    imageTag: string,
    slug: string,
    environment: EnvironmentName
  ) => {
    const image = await deps.docker.buildImage(sourceContainerId, imageTag, "Dockerfile", [
      { name: "Dockerfile", content: PRODUCTION_DOCKERFILE },
      { name: ".dockerignore", content: PRODUCTION_DOCKERIGNORE },
      { name: ".env.production", content: buildDeploymentEnvironment(slug, environment) }
    ]);
    return image.imageId;
  };
  // Shared deploy flow: materialize an env-scoped image from a source container, start a SEPARATE
  // container for that environment, health-gate it, and record the deployment. `publish` builds the
  // image from the dev container's /workspace (real Dockerfile); `promote` snapshots the validated
  // staging container. The `prepareImage` strategy is what differs between the two.
  const deployFromContainer = async (input: {
    projectId: string;
    slug: string;
    environment: EnvironmentName;
    commitSha: string;
    sourceContainerId: string;
    publishedByUserId: string;
    fence?: ProjectMutationFence;
    prepareImage: (
      sourceContainerId: string,
      imageTag: string,
      slug: string,
      environment: EnvironmentName
    ) => Promise<string>;
  }): Promise<PublishOutcome> => {
    const { environment } = input;
    // Materialize an immutable deployment artifact. The source commit remains visible in the tag,
    // while the deployment nonce prevents a repeat publish of the same commit from moving a tag
    // that an older revision already recorded.
    const revisionSuffix = `${input.commitSha.slice(0, 12)}-${randomUUID().slice(0, 8)}`;
    const imageTag = `evcp-${environment}-${input.slug}:${revisionSuffix}`;
    const imageDigest = await input.prepareImage(
      input.sourceContainerId,
      imageTag,
      input.slug,
      environment
    );
    // DB isolation note: staging reuses the project's resolveEnv (same DATABASE_URL) but gets its
    // own container + volume — true staging-DB isolation (separate schema/database) is a follow-up.
    const spec = buildAppContainerSpec(
      {
        projectId: input.projectId,
        slug: input.slug,
        image: imageTag,
        env: await deps.resolveEnv(input.projectId),
        network
      },
      environment
    );
    const containerName = deploymentContainerName(input.slug, environment, revisionSuffix);
    spec.name = containerName;
    spec.labels["evcp.commit-sha"] = input.commitSha;
    spec.labels["evcp.container-name"] = containerName;
    const containerId = await createAndStartFencedContainer({ docker: deps.docker, spec, fence: input.fence });

    let finalized!: WorkspaceDeployment;
    let healthy: boolean;
    let deploymentFlushed = false;
    let deployment: WorkspaceDeployment | undefined;
    try {
      // Queue the pending revision and its health result as one durable lifecycle batch. Prisma
      // stores commit both writes atomically when flush is called below.
      await input.fence?.assertCurrent();
      deployment = deps.deployments.create({
        projectId: input.projectId,
        slug: input.slug,
        environment,
        commitSha: input.commitSha,
        imageTag,
        imageDigest,
        containerId,
        containerName,
        publishedByUserId: input.publishedByUserId
      });

      const basePath =
        environment === "staging" ? `/apps/${input.slug}/staging` : `/apps/${input.slug}`;
      healthy = await deps.health.check(`http://${containerName}:3000${basePath}/api/health`);
      finalized = deps.deployments.updateHealth(deployment.id, healthy ? "healthy" : "failed");
      await input.fence?.assertCurrent();
      await deps.deployments.flush?.();
      deploymentFlushed = true;
      await input.fence?.assertCurrent();
    } catch (error) {
      // Persistence and health-check failures happen after the candidate starts. It must never
      // survive as an unmanaged phantom when the lifecycle cannot be finalized.
      if (deployment && finalized && deploymentFlushed) {
        if (deps.deployments.remove) deps.deployments.remove(deployment.id);
        else deps.deployments.updateHealth(deployment.id, "failed");
        await deps.deployments.flush?.().catch(() => undefined);
      } else if (deployment) deps.deployments.discard(deployment.id);
      await deps.docker.stopContainer(containerId).catch(() => undefined);
      await deps.docker.removeContainer(containerId).catch(() => undefined);
      throw error;
    }

    if (!healthy) {
      // keep old version live; tear down the failed container (best-effort)
      await deps.docker.stopContainer(containerId).catch(() => undefined);
      await deps.docker.removeContainer(containerId).catch(() => undefined);
      audit("workspace.deploy_failed", input.projectId, {
        slug: input.slug,
        environment,
        commitSha: input.commitSha,
        deploymentId: finalized.id
      });
      return { ok: false, reason: "health_failed", deployment: finalized };
    }

    audit("workspace.deploy", input.projectId, {
      slug: input.slug,
      environment,
      commitSha: input.commitSha,
      imageTag,
      deploymentId: finalized.id
    });
    return { ok: true, deployment: finalized };
  };

  return {
    async deleteProject(projectId: string): Promise<void> {
      await withProjectLock(projectId, async () => {
        const deployments = deps.deployments.list(projectId);
        const failures: Error[] = [];
        const attempt = async (cleanup: () => Promise<void>): Promise<void> => {
          try {
            await cleanup();
          } catch (error) {
            failures.push(error instanceof Error ? error : new Error(String(error)));
          }
        };
        for (const deployment of deployments) {
          let container: Awaited<ReturnType<typeof deps.docker.inspectContainer>> | undefined;
          await attempt(async () => {
            container = await deps.docker.inspectContainer(deployment.containerName);
          });
          const containerId =
            container?.containerId ?? (container === undefined ? deployment.containerId : null);
          if (!containerId) continue;
          await attempt(() => deps.docker.stopContainer(containerId));
          await attempt(() => deps.docker.removeContainer(containerId));
        }
        if (failures.length > 0) {
          throw new AggregateError(
            failures,
            `Deployment cleanup did not finish for project '${projectId}'`
          );
        }
        deps.deployments.removeProject(projectId);
        await deps.deployments.flush?.();
        try {
          audit("workspace.deployments_deleted", projectId, { count: deployments.length });
        } catch {
          // Deployment cleanup and persistence have completed; audit failure is best effort here.
        }
      });
    },

    async deactivate(deployment: WorkspaceDeployment): Promise<void> {
      deps.deployments.updateHealth(deployment.id, "failed");
      await deps.deployments.flush?.();
      if (deployment.containerId) {
        await deps.docker.stopContainer(deployment.containerId).catch(() => undefined);
        await deps.docker.removeContainer(deployment.containerId).catch(() => undefined);
      }
      audit("workspace.deploy_compensated", deployment.projectId, {
        slug: deployment.slug,
        environment: deployment.environment,
        commitSha: deployment.commitSha,
        deploymentId: deployment.id
      });
    },

    async publish(input: {
      projectId: string;
      slug: string;
      environment: EnvironmentName;
      commitSha?: string;
      publishedByUserId: string;
    }): Promise<PublishOutcome> {
      const publish = (fence?: ProjectMutationFence): Promise<PublishOutcome> =>
        withProjectLock(input.projectId, async () => {
          const isRollback = Boolean(input.commitSha);
          const devContainerId = await deps.getDevContainerId(input.projectId);

          // Resolve target commit (explicit = rollback/older; else current HEAD).
          const commitSha = input.commitSha ?? (await deps.git.currentCommit(input.projectId));
          audit(isRollback ? "workspace.rollback" : "workspace.publish", input.projectId, {
            slug: input.slug,
            environment: input.environment,
            commitSha
          });

          // Pre-publish checks are deliberately lightweight: the image build below is the single
          // isolated build step. Never invoke `npm run build` in the active dev container.
          const checks = await runPrePublishChecks(
            { git: deps.git, migrations: deps.migrations },
            { projectId: input.projectId, commitSha }
          );
          if (!checks.ok) {
            audit("workspace.publish_rejected", input.projectId, {
              slug: input.slug,
              environment: input.environment,
              failures: checks.failures
            });
            return { ok: false, reason: "pre_checks_failed", failures: checks.failures };
          }

          // Do not mutate the live development checkout until every rollback boundary has passed.
          // A rejected rollback must leave the current healthy source and preview untouched.
          const originalCommit = isRollback ? await deps.git.currentCommit(input.projectId) : null;
          if (isRollback) await deps.git.checkoutCommit(input.projectId, commitSha);

          try {
            return await withDeployQueue(() =>
              deployFromContainer({
                projectId: input.projectId,
                slug: input.slug,
                environment: input.environment,
                commitSha,
                sourceContainerId: devContainerId,
                publishedByUserId: input.publishedByUserId,
                fence,
                prepareImage: buildProductionImage
              })
            );
          } finally {
            if (originalCommit) await deps.git.checkoutCommit(input.projectId, originalCommit);
          }
        });
      return withLifecycle(input.projectId, publish);
    },

    // Promote the current HEALTHY staging source commit to production. Next.js basePath is compiled
    // at build time, so a staging image cannot be reused at the production route. Rebuild the same
    // validated commit with production environment input, then restore the developer's current HEAD.
    async promote(input: {
      projectId: string;
      slug: string;
      publishedByUserId: string;
    }): Promise<PublishOutcome> {
      const promote = (fence?: ProjectMutationFence): Promise<PublishOutcome> =>
        withProjectLock(input.projectId, async () => {
          const staging = deps.deployments.getCurrent(input.slug, "staging");
          if (!staging) {
            throw new Error(`no healthy staging deployment to promote for slug '${input.slug}'`);
          }
          const sourceContainerId = await deps.getDevContainerId(input.projectId);
          const originalCommit = await deps.git.currentCommit(input.projectId);

          audit("workspace.promote", input.projectId, {
            slug: input.slug,
            commitSha: staging.commitSha,
            fromDeploymentId: staging.id
          });

          await deps.git.checkoutCommit(input.projectId, staging.commitSha);
          try {
            return await withDeployQueue(() =>
              deployFromContainer({
                projectId: input.projectId,
                slug: input.slug,
                environment: "production",
                commitSha: staging.commitSha,
                sourceContainerId,
                publishedByUserId: input.publishedByUserId,
                fence,
                prepareImage: buildProductionImage
              })
            );
          } finally {
            await deps.git.checkoutCommit(input.projectId, originalCommit);
          }
        });
      return withLifecycle(input.projectId, promote);
    }
  };
}
